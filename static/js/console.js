const root = document.querySelector("[data-console]");
if (root) setUpConsole(root);

function setUpConsole(root) {
    const config = JSON.parse(document.getElementById("console-config").textContent());
    const output = root.querySelector("[data-console-output]");
    const form = root.querySelector("[data-console-form]");
    const input = root.querySelector("[data-console-input]");
    const startButton = root.querySelector("[data-console-start]");
    const stopButton = root.querySelector("[data-console-stop]");
    const exampleButtons = document.querySelectorAll("[data-console-example]");

    const history = [];
    let historyIndex = 0;
    let worker = null;
    let busy = true;

    function print(text, className = "") {
        const line = document.createElement("div");
        line.textContent = text || " ";
        if (className) line.className = className;
        output.append(line);
        output.scrollTop = output.scrollHeight;
    }

    function showImage(base64Png) {
        const img = document.createElement("img");
        img.src = `data:image/png;base64,${base64Png}`;
        img.alt = "Plot generated by the script";
        img.className = "my-2 max-w-full rounded bg-white";
        img.addEventListener("load", () => (output.scrollTop = output.scrollHeight));
        output.append(img);
    }
}